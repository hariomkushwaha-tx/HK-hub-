/**
 * Quick helper to retrieve localized UI string with automatic fallback to English
 */
export function t(key: string, lang: SupportedLanguage = 'en'): string {
  const entry = UI_TRANSLATIONS[key];
  if (!entry) return key;
  return entry[lang] || entry['en'] || key;
}

/**
 * Get language metadata by code
 */
export function getLanguageMeta(code: SupportedLanguage): LanguageOption {
  return LANGUAGES_LIST.find(l => l.code === code) || LANGUAGES_LIST[2]; // fallback to English
}

export const SUPPORTED_LANGUAGES = LANGUAGES_LIST;
export type { SupportedLanguage, LanguageOption };
