// Storage key for user/admin custom chapter edits
export const BHARATVARSH_STORAGE_KEY = 'hk_bharatvarsh_custom_edits';

export function getCustomEdits(): Record<number, Partial<BharatvarshChapter>> {
  if (typeof window === 'undefined') return {};
  try {
    const raw = localStorage.getItem(BHARATVARSH_STORAGE_KEY);
    return raw ? JSON.parse(raw) : {};
  } catch (e) {
    console.error('Failed to load Bharatvarsh custom edits', e);
    return {};
  }
}

export function saveCustomChapterEdit(chapterNumber: number, data: Partial<BharatvarshChapter>): void {
  if (typeof window === 'undefined') return;
  try {
    const current = getCustomEdits();
    current[chapterNumber] = { ...(current[chapterNumber] || {}), ...data, lastUpdated: new Date().toISOString().split('T')[0] };
    localStorage.setItem(BHARATVARSH_STORAGE_KEY, JSON.stringify(current));
  } catch (e) {
    console.error('Failed to save Bharatvarsh chapter edit', e);
  }
}

